namespace NBTerminal;

/// <summary>
/// Представляет неизменяемое значение одной ячейки кадра: символ и его оформление.
/// </summary>
/// <param name="Character">Кодовая единица char. Нулевое значение при рендеринге превращается в пробел.</param>
/// <param name="Style">Оформление именно этой ячейки.</param>
/// <remarks>
/// <para>
/// Для изменения ячейки методы Frame заменяют элемент массива новым значением. Сравнение ячеек учитывает и символ, и
/// стиль, что используется построчным разностным рендером.
/// </para>
/// <para>
/// Одна ячейка рассчитана на один поддерживаемый экранный столбец. Сам тип не проверяет ширину символа и не
/// интерпретирует управляющие знаки.
/// </para>
/// </remarks>
public readonly record struct Cell(char Character, Style Style);