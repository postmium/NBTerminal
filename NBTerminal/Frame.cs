using System.Text;

namespace NBTerminal;

/// <summary>
/// Хранит прямоугольный буфер ячеек и виртуальный курсор последовательной записи.
/// </summary>
/// <remarks>
/// <para>
/// Ячейки находятся в одном массиве: индекс равен номеру строки, умноженному на ширину, плюс номер столбца. Методы
/// записи меняют только этот буфер и не отправляют команды терминалу.
/// </para>
/// <para>
/// Курсор принадлежит кадру, а не физической консоли. Запись может переноситься на следующую строку, но содержимое не
/// прокручивается: после нижней границы новые символы не записываются.
/// </para>
/// <para>
/// Методы Write обрабатывают возврат каретки, перевод строки и табуляцию. Широкие символы, составные графемы и
/// суррогатные пары не поддерживаются как отдельные экранные знаки.
/// </para>
/// <para>
/// Кадры, выданные Terminal в событиях Output, переиспользуются. Вне своего синхронного обработчика не изменяйте такой
/// кадр и не полагайтесь на сохранённую ссылку как на неизменяемую копию.
/// </para>
/// </remarks>
public class Frame
{
    //Ячейки хранятся построчно в одном массиве; размеры не меняются после создания кадра.
    //Длина массива равна width × height.
    private readonly Cell[] _buffer;
    private readonly int width;
    private readonly int height;

    /// <summary>
    /// Возвращает количество ячеек в строке.
    /// </summary>
    /// <value>
    /// Неотрицательная ширина, зафиксированная конструктором.
    /// </value>
    public int Width => width;

    /// <summary>
    /// Возвращает количество строк кадра.
    /// </summary>
    /// <value>
    /// Неотрицательная высота, зафиксированная конструктором.
    /// </value>
    public int Height => height;

    /// <summary>
    /// Предоставляет рендеру представление массива ячеек только для чтения.
    /// </summary>
    /// <value>
    /// Все ячейки в построчном порядке, без копирования массива.
    /// </value>
    /// <remarks>
    /// <para>
    /// Это представление, а не снимок. Изменения через методы Frame видны в том же массиве; ограничение чтения
    /// относится только к полученному представлению.
    /// </para>
    /// </remarks>
    internal ReadOnlySpan<Cell> Buffer => _buffer;

    //Виртуальная позиция записи. С физическим курсором терминала эти поля не связаны.
    //Столбец виртуального курсора, начиная с нуля.
    private int _cursorX = 0;

    //Строка виртуального курсора; height обозначает конец доступного кадра.
    private int _cursorY = 0;

    //true означает: последний символ занял правый край, перенос ждёт следующей записи.
    private bool _wrapPending = false;

    /// <summary>
    /// Возвращает горизонтальную координату виртуального курсора, начиная с нуля.
    /// </summary>
    /// <value>
    /// Текущий столбец; при пустом кадре исходное значение равно нулю.
    /// </value>
    /// <remarks>
    /// <para>
    /// После записи в последний столбец координата остаётся на нём, а перенос ожидает следующий обычный символ. Поэтому
    /// значение не всегда указывает на ячейку, которую заменит следующая запись.
    /// </para>
    /// </remarks>
    public int CursorLeft => _cursorX;

    /// <summary>
    /// Возвращает вертикальную координату виртуального курсора, начиная с нуля.
    /// </summary>
    /// <value>
    /// Номер строки или Height, когда запись уже вышла за нижнюю границу.
    /// </value>
    /// <remarks>
    /// <para>
    /// Положение за кадром не прокручивает буфер. Вернуться внутрь можно через SetCursorPosition или ResetCursor.
    /// </para>
    /// </remarks>
    public int CursorTop => _cursorY;

    /// <summary>
    /// Создаёт пустой кадр заданного размера с курсором в начале.
    /// </summary>
    /// <param name="width">Количество столбцов; ноль разрешён.</param>
    /// <param name="height">Количество строк; ноль разрешён.</param>
    /// <remarks>
    /// <para>
    /// Ячейки получают нулевой char и стиль по умолчанию. При нулевой ширине или высоте буфер не содержит ячеек.
    /// </para>
    /// </remarks>
    /// <exception cref="ArgumentOutOfRangeException">Ширина или высота меньше нуля.</exception>
    /// <exception cref="OverflowException">Произведение ширины и высоты не помещается в int.</exception>
    public Frame(int width, int height)
    {
        //Отрицательные размеры запрещены, но нулевой размер допустим.
        ArgumentOutOfRangeException.ThrowIfNegative(width);
        ArgumentOutOfRangeException.ThrowIfNegative(height);

        this.width = width;
        this.height = height;

        //checked предотвращает переполнение int при вычислении количества ячеек.
        _buffer = new Cell[checked(width * height)];
    }

    /// <summary>
    /// Заменяет одну ячейку по линейному индексу, не меняя курсор.
    /// </summary>
    /// <param name="index">Индекс в массиве: строка × Width + столбец.</param>
    /// <param name="cell">Символ и стиль, которыми нужно заменить ячейку.</param>
    /// <remarks>
    /// <para>
    /// Индекс вне массива молча игнорируется. Управляющие символы здесь не интерпретируются и не заменяются: значение
    /// сохраняется как передано.
    /// </para>
    /// </remarks>
    public void Set(int index, Cell cell)
    {
        //Одна проверка диапазона отсекает и отрицательный индекс, и индекс за концом массива.
        if ((uint)index < (uint)_buffer.Length)
            _buffer[index] = cell;
    }

    /// <summary>
    /// Заменяет ячейку по координатам, не меняя курсор.
    /// </summary>
    /// <param name="x">Номер столбца начиная с нуля.</param>
    /// <param name="y">Номер строки начиная с нуля.</param>
    /// <param name="cell">Новое значение ячейки.</param>
    /// <remarks>
    /// <para>
    /// Если хотя бы одна координата находится вне кадра, ничего не записывает. В отличие от Write, напрямую сохраняет
    /// переданный char без обработки управляющих символов.
    /// </para>
    /// </remarks>
    public void Set(int x, int y, Cell cell)
    {
        //Проверяем координаты отдельно, чтобы x за правой границей не попал в следующую строку.
        if ((uint)x < (uint)width && (uint)y < (uint)height)
            _buffer[y * width + x] = cell;
    }

    /// <summary>
    /// Устанавливает виртуальный курсор внутрь кадра и отменяет ожидающий перенос.
    /// </summary>
    /// <param name="x">Столбец от нуля до Width минус один.</param>
    /// <param name="y">Строка от нуля до Height минус один.</param>
    /// <exception cref="ArgumentOutOfRangeException">
    /// Одна из координат находится вне кадра. У кадра с нулевой шириной или высотой допустимой позиции нет.
    /// </exception>
    public void SetCursorPosition(int x, int y)
    {
        if ((uint)x >= (uint)width) throw new ArgumentOutOfRangeException(nameof(x));
        if ((uint)y >= (uint)height) throw new ArgumentOutOfRangeException(nameof(y));

        _cursorX = x;
        _cursorY = y;
        _wrapPending = false;
    }

    /// <summary>
    /// Возвращает виртуальный курсор в (0, 0) и отменяет ожидающий перенос.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Не очищает ячейки. Разрешён и для пустого кадра, хотя запись в него остаётся невозможной.
    /// </para>
    /// </remarks>
    public void ResetCursor()
    {
        _cursorX = 0;
        _cursorY = 0;
        _wrapPending = false;
    }

    /// <summary>
    /// Переводит виртуальный курсор к началу следующей строки.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Не изменяет буфер. Высота служит предельным значением CursorTop; после её достижения новые вызовы не увеличивают
    /// номер строки.
    /// </para>
    /// </remarks>
    private void NewLine()
    {
        //Переход строки меняет только курсор и отменяет ожидающий перенос.
        _cursorX = 0;
        if (_cursorY < height) _cursorY++;
        _wrapPending = false;
    }

    /// <summary>
    /// Записывает одну ячейку в текущую позицию с учётом ожидающего переноса.
    /// </summary>
    /// <param name="character">Символ для записи; управляющий char и суррогат заменяются пробелом.</param>
    /// <param name="style">Стиль записываемой ячейки.</param>
    /// <remarks>
    /// <para>
    /// За нижней границей и при нулевой ширине ничего не делает. Последний столбец не переносит курсор сразу:
    /// устанавливается флаг для следующей записи.
    /// </para>
    /// </remarks>
    private void WriteCharacter(char character, Style style)
    {
        //При пустой ширине или курсоре за последней строкой не записываем ячейку.
        if (width == 0 || _cursorY >= height) return;

        //Последний столбец был занят раньше; перенос выполняем только перед следующим обычным символом.
        if (_wrapPending) NewLine();

        //Перенос мог вывести курсор за нижнюю границу — прокрутки здесь нет.
        if (_cursorY >= height) return;

        //Перевод строки, возврат каретки и табуляция уже разобраны выше в WriteText.
        if (char.IsControl(character) || char.IsSurrogate(character))
            character = ' ';

        //Заменяем значение элемента массива: неизменяемые Character и Style хранятся вместе.
        _buffer[_cursorY * width + _cursorX] = new Cell(character, style);

        //Справа оставляем курсор на последнем столбце и помечаем ожидающий перенос.
        if (_cursorX == width - 1)
            _wrapPending = true;
        else
            _cursorX++;
    }

    /// <summary>
    /// Разбирает текст и записывает его в ячейки с одним общим стилем.
    /// </summary>
    /// <param name="text">Последовательность кодовых единиц char.</param>
    /// <param name="style">Оформление всех записываемых символов и пробелов табуляции.</param>
    /// <remarks>
    /// <para>
    /// <c>
    /// </c> возвращает курсор в начало текущей строки и отменяет ожидающий перенос; <c>
    /// </c> переходит к началу следующей строки.
    /// </para>
    /// <para>
    /// <c> </c> сначала выполняет ожидающий перенос, затем записывает от 1 до 8 пробелов до следующего вычисленного
    /// шага табуляции. Эти пробелы подчиняются обычным границам и могут перенестись на следующую строку.
    /// </para>
    /// <para>
    /// Даже когда места больше нет, метод продолжает разбирать оставшиеся символы текста; записи за нижней границей
    /// игнорируются.
    /// </para>
    /// </remarks>
    private void WriteText(ReadOnlySpan<char> text, Style style)
    {
        foreach (char character in text)
        {
            //Эти три управляющих символа меняют виртуальную запись; остальные попадут в обычную обработку.
            switch (character)
            {
                case '\r':

                    //Возврат каретки не стирает строку и не меняет номер строки.
                    _cursorX = 0;
                    _wrapPending = false;
                    break;

                case '\n':

                    //Перевод строки всегда идёт к её началу; даже при ожидающем переносе переход один.
                    NewLine();
                    break;

                case '\t':

                    //Табуляция после правого края рассчитывается уже от начала новой строки.
                    if (_wrapPending) NewLine();

                    //Следующая условная позиция табуляции кратна восьми; записываем нужное число пробелов.
                    int spaces = 8 - (_cursorX % 8);

                    for (int i = 0; i < spaces; i++)
                        WriteCharacter(' ', style);
                    break;

                default:
                    WriteCharacter(character, style);
                    break;
            }
        }
    }

    /// <summary>
    /// Записывает обычный текст с оформлением по умолчанию.
    /// </summary>
    /// <param name="text">Текст; <see langword="null"/> и пустая строка ничего не записывают.</param>
    /// <remarks>
    /// <para>
    /// Продолжает запись с виртуального курсора. Обрабатывает <c>
    /// </c>, <c>
    /// </c> и <c> </c>; при заполнении правой границы следующий обычный символ переносится. За нижней границей запись
    /// прекращается без прокрутки.
    /// </para>
    /// <para>
    /// Уже существующий хвост строки не стирается автоматически. Неподдерживаемые управляющие символы и отдельные
    /// суррогаты заменяются пробелами.
    /// </para>
    /// <para>
    /// Не наследует стиль предыдущего вызова Write со стилизованной строкой.
    /// </para>
    /// </remarks>
    public void Write(string? text)
    {
        WriteText(text.AsSpan(), default);
    }

    /// <summary>
    /// Записывает стилизованный текст, перенося его стиль в каждую записанную ячейку.
    /// </summary>
    /// <param name="text">Текст и общее оформление; пустой текст не меняет буфер.</param>
    /// <remarks>
    /// <para>
    /// Продолжает запись с виртуального курсора. Обрабатывает <c>
    /// </c>, <c>
    /// </c> и <c> </c>; при заполнении правой границы следующий обычный символ переносится. За нижней границей запись
    /// прекращается без прокрутки.
    /// </para>
    /// <para>
    /// Уже существующий хвост строки не стирается автоматически. Неподдерживаемые управляющие символы и отдельные
    /// суррогаты заменяются пробелами.
    /// </para>
    /// <para>
    /// Для <c>default(StyledString)</c> отсутствующий текст трактуется как пустой. Последующие обычные строки снова
    /// используют оформление по умолчанию.
    /// </para>
    /// </remarks>
    public void Write(StyledString text)
    {
        WriteText(text.Text.AsSpan(), text.Style);
    }

    /// <summary>
    /// Записывает один char с оформлением по умолчанию.
    /// </summary>
    /// <param name="character">Символ или поддерживаемый управляющий знак.</param>
    /// <remarks>
    /// <para>
    /// Использует те же правила, что и Write(string): перевод строки, возврат каретки и табуляция обрабатываются как
    /// команды виртуальному курсору, а не сохраняются буквальными ячейками.
    /// </para>
    /// </remarks>
    public void Write(char character)
    {
        //Один char на стеке позволяет использовать общий разбор управляющих символов.
        Span<char> buffer = stackalloc char[1];
        buffer[0] = character;
        WriteText(buffer, default);
    }

    /// <summary>
    /// Записывает значение, выбирая обработку по его фактическому типу.
    /// </summary>
    /// <param name="value">Значение для записи; <see langword="null"/> ничего не делает.</param>
    /// <remarks>
    /// <para>
    /// StyledString записывается с сохранением стиля, string и char передаются соответствующим перегрузкам. Для
    /// остальных типов вызывается ToString и записывается полученная обычная строка.
    /// </para>
    /// <para>
    /// Преобразование объекта может выделять память и выбрасывать исключения; этот метод их не перехватывает. Упаковка
    /// значимого типа в object также не устраняется.
    /// </para>
    /// </remarks>
    public void Write(object? value)
    {
        switch (value)
        {
            //Проверяем StyledString до общего ToString, чтобы не потерять оформление.
            case StyledString styled:
                Write(styled);
                break;

            case string text:
                Write(text);
                break;

            case char character:
                Write(character);
                break;

            case null:
                break;

            default:

                //Исключение пользовательского ToString не перехватываем; вызывающий код решает, как его обработать.
                Write(value.ToString());
                break;
        }
    }

    /// <summary>
    /// Переводит виртуальный курсор к началу следующей строки без записи символов.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Отменяет ожидающий перенос после последнего столбца, не очищает строки и не прокручивает буфер. После нижней
    /// границы CursorTop остаётся равным Height.
    /// </para>
    /// </remarks>
    public void WriteLine()
    {
        NewLine();
    }

    /// <summary>
    /// Записывает обычную строку и затем переходит к началу следующей.
    /// </summary>
    /// <param name="text">Текст; при <see langword="null"/> выполняется только переход строки.</param>
    /// <remarks>
    /// <para>
    /// Использует Write(string), затем один вызов перехода строки. Переводы строк внутри самого текста также
    /// выполняются. После записи ровно на ширину кадра ожидающий автоперенос не создаёт лишнюю пустую строку.
    /// </para>
    /// </remarks>
    public void WriteLine(string? text)
    {
        Write(text);
        NewLine();
    }

    /// <summary>
    /// Записывает стилизованную строку и затем переходит к началу следующей.
    /// </summary>
    /// <param name="text">Текст с общим оформлением.</param>
    /// <remarks>
    /// <para>
    /// Стиль сохраняется в записанных ячейках. При пустом тексте всё равно выполняется переход строки; дальнейшие
    /// обычные записи используют оформление по умолчанию.
    /// </para>
    /// </remarks>
    public void WriteLine(StyledString text)
    {
        Write(text);
        NewLine();
    }

    /// <summary>
    /// Записывает значение по правилам Write(object) и затем переходит к следующей строке.
    /// </summary>
    /// <param name="value">Записываемое значение; при <see langword="null"/> выполняется только переход.</param>
    /// <remarks>
    /// <para>
    /// Если преобразование или запись выбрасывает исключение, последующий переход строки не выполняется.
    /// </para>
    /// </remarks>
    public void WriteLine(object? value)
    {
        Write(value);
        NewLine();
    }

    /// <summary>
    /// Обнуляет все ячейки и возвращает виртуальный курсор в начало.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Переиспользует существующий массив. Каждая ячейка становится сочетанием нулевого char и стиля по умолчанию; это
    /// не очистка физического экрана терминала.
    /// </para>
    /// </remarks>
    public void Clear()
    {
        //Меняем существующие ячейки на default, не создавая новый массив.
        Array.Clear(_buffer);
        ResetCursor();
    }

    /// <summary>
    /// Создаёт текстовое представление всего прямоугольного буфера без оформления.
    /// </summary>
    /// <returns>
    /// Строки полной ширины, разделённые переводами строки среды; после последней строки разделитель не добавляется.
    /// </returns>
    /// <remarks>
    /// <para>
    /// Нулевые char заменяются пробелами. Другие символы, напрямую записанные через Set, возвращаются как есть; стили
    /// не включаются.
    /// </para>
    /// <para>
    /// Метод создаёт строковое представление для чтения или диагностики. Рендер не использует его для формирования
    /// команды и читает ячейки напрямую.
    /// </para>
    /// </remarks>
    public override string ToString()
    {
        StringBuilder result = new();

        for (int y = 0; y < height; y++)
        {
            for (int x = 0; x < width; x++)
            {
                //Только нулевой символ заменяется пробелом; остальные значения Set возвращаются как записаны.
                char character = _buffer[y * width + x].Character;
                result.Append(character == '\0' ? ' ' : character);
            }

            //Разделитель добавляется между строками, но не после последней.
            if (y < height - 1)
                result.AppendLine();
        }

        return result.ToString();
    }
